<#
.SYNOPSIS
    Generates the PSCloudPC cmdlet reference for the Docusaurus website.

.DESCRIPTION
    Imports the PSCloudPC module from a local checkout and uses Alt3.Docusaurus.Powershell
    (on top of PlatyPS) to generate one .mdx page per exported cmdlet into
    website/docs/commands, together with a docusaurus.sidebar.js include file and a
    generated overview page (index.md) that lists every cmdlet with its synopsis.

    Generated help is post-processed so it is safe for MDX: PlatyPS placeholders are
    replaced, the synopsis is written to the front matter description and the edit link
    points at the cmdlet's source file in the PSCloudPC repository.

    If you are running the Docusaurus dev server, restart it after running this script
    to clear any "Module not found" errors.

.PARAMETER ModulePath
    Path to the PSCloudPC module manifest (PSCloudPC.psd1). Defaults to a sibling checkout
    of the module repository: ../PSCloudPC/PSCloudPc/PSCloudPC.psd1 relative to the
    root of this repository.

.PARAMETER WebsitePath
    Path to the Docusaurus project. Defaults to the website folder next to this script's
    parent folder.

.PARAMETER EditUrlBase
    Base URL used for the "Edit this page" link of each cmdlet page. The cmdlet's source
    file name is appended to it.

.EXAMPLE
    ./build/Update-CommandReference.ps1

    Generates the reference from a sibling PSCloudPC checkout.

.EXAMPLE
    ./build/Update-CommandReference.ps1 -ModulePath ~/repositories/PSCloudPC/PSCloudPc/PSCloudPC.psd1

    Generates the reference from a specific module checkout.
#>
[CmdletBinding()]
param(
    [Parameter()]
    [string]$ModulePath = (Join-Path $PSScriptRoot '../../PSCloudPC/PSCloudPc/PSCloudPC.psd1'),

    [Parameter()]
    [string]$WebsitePath = (Join-Path $PSScriptRoot '../website'),

    [Parameter()]
    [string]$EditUrlBase = 'https://github.com/Windows365Management/PSCloudPC/blob/develop/PSCloudPc/Public/'
)

$ErrorActionPreference = 'Stop'

# Alt3 2.x requires Microsoft.PowerShell.PlatyPS, whose YamlDotNet assembly conflicts with legacy PlatyPS.
# Keep both versions pinned together.
$alt3DocusaurusVersion = '1.0.37'
$platyPSVersion = '0.14.2'

foreach ($dependency in @(
        @{ Name = 'Alt3.Docusaurus.Powershell'; Version = $alt3DocusaurusVersion }
        @{ Name = 'PlatyPS'; Version = $platyPSVersion }
    )) {
    if (-not (Get-Module $dependency.Name -ListAvailable | Where-Object { $_.Version -eq $dependency.Version })) {
        Write-Host "Installing $($dependency.Name) $($dependency.Version)"
        Install-Module $dependency.Name -RequiredVersion $dependency.Version -Scope CurrentUser -Force -SkipPublisherCheck
    }
}

Import-Module Alt3.Docusaurus.Powershell -RequiredVersion $alt3DocusaurusVersion -Force
Import-Module PlatyPS -RequiredVersion $platyPSVersion -Force

# Resolve paths
if (-not (Test-Path $ModulePath)) {
    throw "PSCloudPC module manifest not found at '$ModulePath'. Clone Windows365Management/PSCloudPC next to this repository or pass -ModulePath."
}
$ModulePath = (Resolve-Path $ModulePath).Path
$WebsitePath = (Resolve-Path $WebsitePath).Path
$docsFolder = Join-Path $WebsitePath 'docs'
$commandsFolder = Join-Path $docsFolder 'commands'

# Import the module from the checkout (not from the gallery) so docs match the source
Get-Module PSCloudPC | Remove-Module -Force
$module = Import-Module $ModulePath -Force -PassThru
Write-Host "Generating command reference for $($module.Name) $($module.Version) from $ModulePath"

# Generate the .mdx files and docusaurus.sidebar.js (this cleans the commands folder first)
$docusaurusHelpParams = @{
    Module                = $module.Name
    DocsFolder            = $docsFolder
    Sidebar               = 'commands'
    EditUrl               = $EditUrlBase
    MetaKeywords          = @('PowerShell', 'PSCloudPC', 'Windows 365', 'Cloud PC', 'Microsoft Graph')
    NoPlaceHolderExamples = $true
}
New-DocusaurusHelp @docusaurusHelpParams | Out-Null

$commandFiles = Get-ChildItem $commandsFolder -Filter *.mdx | Sort-Object BaseName

# PlatyPS adds placeholders for common parameters that have no help text
$generatedParameterDescriptions = @{
    ProgressAction = 'Determines how PowerShell responds to progress updates generated by a script, cmdlet, or provider, such as the progress bars generated by Write-Progress.'
}

# Text replacements that keep generated help valid MDX. Alt3 escapes < > { } but some
# comment-based help still contains constructs MDX cannot parse.
$mdxReplacements = [ordered]@{
    # Bare URLs inside angle brackets are already HTML-encoded by Alt3; turn them back into autolinks
    '&lt;(https?://[^\s&]+)&gt;' = '$1'
}

$overviewRows = foreach ($file in $commandFiles) {
    $content = Get-Content $file.FullName -Raw

    foreach ($parameterName in $generatedParameterDescriptions.Keys) {
        $description = $generatedParameterDescriptions[$parameterName]
        $content = $content.Replace("\{\{ Fill $parameterName Description \}\}", $description)
        $content = $content.Replace("{{ Fill $parameterName Description }}", $description)
    }

    # Parameters without a .PARAMETER entry in the comment-based help get a PlatyPS placeholder.
    # Report them so the help can be fixed in the module, and keep the placeholder off the site.
    $missingParameterHelp = [regex]::Matches($content, '\\?\{\\?\{ Fill (\w+) Description \\?\}\\?\}')
    foreach ($match in $missingParameterHelp) {
        Write-Warning "$($file.BaseName): parameter -$($match.Groups[1].Value) has no description in the comment-based help."
    }
    $content = [regex]::Replace($content, '\\?\{\\?\{ Fill \w+ Description \\?\}\\?\}', '_No description available._')

    foreach ($pattern in $mdxReplacements.Keys) {
        $content = $content -replace $pattern, $mdxReplacements[$pattern]
    }

    # Pull the synopsis (first non-empty line after ## SYNOPSIS)
    $synopsis = ''
    $synopsisMatch = [regex]::Match($content, '(?ms)^## SYNOPSIS\s*\n+(.+?)\n')
    if ($synopsisMatch.Success) {
        $synopsis = $synopsisMatch.Groups[1].Value.Trim()
    }
    $isPlaceholder = $synopsis -match '^\s*\\?\{\\?\{\s*Fill in the Synopsis\s*\\?\}\\?\}\s*$'
    if ($isPlaceholder) {
        Write-Warning "$($file.BaseName) has no synopsis in its comment-based help."
        $synopsis = ''
    }

    # Front matter: use the synopsis as the page (meta) description.
    if ($synopsis) {
        $plainSynopsis = $synopsis -replace '\\([{}<>])', '$1' -replace '&lt;', '<' -replace '&gt;', '>'
        $yamlSynopsis = $plainSynopsis.Replace('\', '\\').Replace('"', '\"')
        $content = [regex]::Replace($content, '(?m)^id:', "description: `"$yamlSynopsis`"`nid:", 1)
    }

    Set-Content -Path $file.FullName -Value $content -NoNewline

    [pscustomobject]@{
        Name     = $file.BaseName
        Synopsis = $synopsis
    }
}

# Generate the overview page. It is regenerated on every run, so do not edit it by hand.
$tableRows = foreach ($row in $overviewRows) {
    $cellSynopsis = $row.Synopsis -replace '\|', '\|'
    "| [$($row.Name)](./$($row.Name).mdx) | $cellSynopsis |"
}

$overview = @"
---
id: index
title: Cmdlet reference
sidebar_label: Overview
sidebar_position: 1
description: Reference documentation for every cmdlet in the PSCloudPC PowerShell module.
---

{/* This file is generated by build/Update-CommandReference.ps1. Do not edit it by hand. */}

The PSCloudPC module exports **$($overviewRows.Count) cmdlets**. Every page below is generated from the
comment-based help in the [PSCloudPC repository](https://github.com/Windows365Management/PSCloudPC/tree/develop/PSCloudPc/Public),
so you can get the same information in your shell:

``````powershell
Get-Command -Module PSCloudPC
Get-Help Get-CloudPC -Full
``````

Not connected yet? Start with [Connect-Windows365](./Connect-Windows365.mdx) and the
[authentication guide](../getting-started/authentication.md).

| Cmdlet | Description |
| --- | --- |
$($tableRows -join "`n")
"@

Set-Content -Path (Join-Path $commandsFolder 'index.md') -Value $overview

$exported = @($module.ExportedFunctions.Keys + $module.ExportedCmdlets.Keys) | Sort-Object -Unique
Write-Host "Generated $($commandFiles.Count) command pages for $($exported.Count) exported commands in $commandsFolder"
if ($commandFiles.Count -ne $exported.Count) {
    Write-Warning "Number of generated pages ($($commandFiles.Count)) does not match the number of exported commands ($($exported.Count))."
}
